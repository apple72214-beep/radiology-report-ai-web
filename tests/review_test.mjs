import assert from 'node:assert/strict';
import {reportReview,privateGeometryReport,referenceReason} from '../app.v149.js';
const base={exam:'MRI Brain with and without IV contrast',technique:'MRI performed without intravenous contrast.',findings:['No abnormal enhancement on post-contrast imaging.'],impression:['Review']} ;
assert(reportReview(base).some(x=>x.code==='contrast-conflict'));
assert(!reportReview({...base,technique:'MRI without and with intravenous contrast.'}).some(x=>x.code==='contrast-conflict'));
assert(!reportReview({...base,exam:'MRI Brain without IV contrast',findings:['No restricted diffusion.']}).some(x=>x.code==='contrast-conflict'));
assert(reportReview({...base,technique:''}).some(x=>x.code==='missing-technique'));
assert(reportReview({...base,impression:[]}).some(x=>x.code==='missing-impression'));
assert.equal(reportReview(null).length,0);
const a={patient:'SENSITIVE',seriesUid:'SECRET-SERIES',data:[1,2,3],w:101,h:101,spacing:[1,1],geometry:{ipp:[0,0,20],iop:[1,0,0,0,1,0],frameOfReferenceUid:'SECRET-REF'}};
const b={...a,geometry:{...a.geometry,ipp:[30,0,0],iop:[0,1,0,0,0,1]}};
assert.equal(referenceReason(a,b),'visible');
assert.equal(referenceReason(a,{...b,spacing:null}),'missing-spacing');
assert.equal(referenceReason(a,{...b,geometry:{...b.geometry,frameOfReferenceUid:'other'}}),'different-reference');
assert.equal(referenceReason(a,{...b,geometry:{...b.geometry,frameOfReferenceUid:''}}),'missing-reference');
assert.equal(referenceReason(a,a),'parallel-planes');
const diag=JSON.stringify(privateGeometryReport(a,b));for(const secret of ['SENSITIVE','SECRET-SERIES','SECRET-REF','"data"','"patient"'])assert(!diag.includes(secret));
assert(privateGeometryReport(a,b).matchingReference);
assert.equal(referenceReason(a,{...b,geometry:{...b.geometry,iop:[0,0,0,0,0,0]}}),'invalid-orientation');
console.log('REVIEW AND PRIVATE GEOMETRY TEST PASS');
